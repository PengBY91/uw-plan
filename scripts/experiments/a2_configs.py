"""Write configs/a2/<family>_<name>.yaml for every candidate in configs/w4_matrix.yaml (refuses to overwrite)."""
import argparse
from pathlib import Path

import yaml


def candidates(matrix):
    base = matrix['shared']['base_sigma']
    s0 = {'enabled': True, 'sigma_range_m': base['range_m'], 'sigma_bearing_deg': base['bearing_deg'], 'kernel': 'none'}
    f = matrix['families']
    for scale in f['fixed_weight']['sigma_scale']:
        yield 'fixed_weight', f'sigma{scale:g}', dict(s0, sigma_range_m=base['range_m']*scale, sigma_bearing_deg=base['bearing_deg']*scale)
    for kind in ['huber', 'cauchy']:
        for k in f['robust_kernel'][f'{kind}_k']:
            yield 'robust_kernel', f'{kind}{k:g}', dict(s0, kernel=kind, kernel_k=k)
    inn = f['scalar_weight']['innovation']
    for w in inn['w_min']:
        for high, low in inn['high_low']:
            yield 'scalar_weight', f'innov_w{w:g}_h{high:g}_l{low:g}', dict(s0, weight={'kind': 'innovation', 'w_min': w, 'high': high, 'low': low, 'ema_alpha': 0.3})
    sup = f['scalar_weight']['support']
    for w in sup['w_min']:
        for n in sup['n_full']:
            yield 'scalar_weight', f'support_w{w:g}_n{n}', dict(s0, weight={'kind': 'support', 'w_min': w, 'n_full': n})


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--matrix', type=Path, default=Path('configs/w4_matrix.yaml'))
    parser.add_argument('--out', type=Path, default=Path('configs/a2'))
    args = parser.parse_args()
    matrix = yaml.safe_load(args.matrix.read_text())
    args.out.mkdir(parents=True, exist_ok=True)
    counts = {}
    for family, name, sonar in candidates(matrix):
        counts[family] = counts.get(family, 0) + 1
        path = args.out/f'{family}_{name}.yaml'
        if path.exists():
            raise SystemExit('Refusing to overwrite ' + str(path))
        path.write_text(f'# Generated by scripts/experiments/a2_configs.py from {args.matrix}; family {family}.\n' +
                        yaml.safe_dump({'backend': {'sonar': sonar}}, sort_keys=False))
    assert all(n <= 10 for n in counts.values()), counts
    print(counts)


if __name__ == '__main__':
    main()
